// Writers for the football snapshot files in data/, the page's fallback when
// Sleeper or FantasyCalc can't be reached. The page only loads them after a
// live fetch fails (loadDataScript in index.html), so most visits never
// download them. One week or one row per line, so a refresh's diff stays small.

// data/nfl-scores.js: {updatedOn, scores: {week: {id: pts}}, dnp: {week: [id]},
// extras: [{id, name, team, position}]}, by scripts/refresh-scores.js.
const SCORES_HEADER = "// Generated by scripts/refresh-scores.js — don't edit by hand.\nwindow.NFL_SCORES = ";

function formatScores({ updatedOn, scores, dnp, extras }) {
  const sortKeys = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  const weeks = (byWeek, f) => Object.keys(byWeek).map((w) => `    ${JSON.stringify(w)}: ${JSON.stringify(f(byWeek[w]))}`).join(",\n");
  return `${SCORES_HEADER}{\n  "updatedOn": ${JSON.stringify(updatedOn)},\n` +
    `  "scores": {\n${weeks(scores, sortKeys)}\n  },\n` +
    `  "dnp": {\n${weeks(dnp, (ids) => [...ids].sort())}\n  },\n` +
    `  "extras": [\n${extras.map((p) => `    ${JSON.stringify({ id: p.id, name: p.name, team: p.team, position: p.position, extra: true })}`).join(",\n")}\n  ]\n};\n`;
}

// data/dynasty-values.js: FantasyCalc's 12-team PPR dynasty values in both QB
// formats, each row a positional array in `fields` order, by
// scripts/refresh-dynasty.js.
const DYNASTY_HEADER = "// Generated by scripts/refresh-dynasty.js — don't edit by hand.\nwindow.DYNASTY_SNAPSHOT = ";
const DYNASTY_FIELDS = ["id", "name", "position", "team", "age", "value", "redraftValue", "overallRank", "posRank", "trend30", "tier", "fcId"];

function formatDynasty({ updatedOn, ...formats }) {
  const rows = (list) => list.map((r) => `    ${JSON.stringify(Array.isArray(r) ? r : DYNASTY_FIELDS.map((k) => r[k] ?? null))}`).join(",\n");
  const body = ["1qb", "sf"].map((f) => `  ${JSON.stringify(f)}: [\n${rows(formats[f])}\n  ]`).join(",\n");
  return `${DYNASTY_HEADER}{\n  "updatedOn": ${JSON.stringify(updatedOn)},\n  "fields": ${JSON.stringify(DYNASTY_FIELDS)},\n${body}\n};\n`;
}

// The data a snapshot file holds (null if it's missing), for comparing before a rewrite.
function readSnapshot(fs, file, header) {
  try {
    const text = fs.readFileSync(file, "utf8");
    return JSON.parse(text.slice(header.length).replace(/;\s*$/, ""));
  } catch (e) {
    return null;
  }
}

module.exports = { formatScores, formatDynasty, readSnapshot, SCORES_HEADER, DYNASTY_HEADER, DYNASTY_FIELDS };
