#!/usr/bin/env node
// Rewrites data/nba-waivers.js, the basketball Waiver Desk's pickup list for
// today, from Sleeper (see lib/nba-waivers.js for how players are picked).
// Run daily by .github/workflows/refresh-nba.yml after the night's games.
//
// Usage: node scripts/refresh-nba-waivers.js [--dry-run]

const fs = require("fs");
const path = require("path");
const N = require("./lib/sleeper-nba");
const { pickNbaWaivers } = require("./lib/nba-waivers");

const OUT = path.join(__dirname, "..", "data", "nba-waivers.js");
const DRY_RUN = process.argv.includes("--dry-run");
const HEADER = "// Generated by scripts/refresh-nba-waivers.js — don't edit by hand.\nwindow.NBA_WAIVERS = ";
// The notes quote points in this scoring; the page says so.
const SCORING = "standard";

async function main() {
  const state = await N.fetchState();
  if (state.season_type !== "regular") return console.log(`Not the regular season (${state.season_type}) — file left as is.`);
  const [season, previous, projections, players, adds, schedule] = await Promise.all([
    N.fetchSeason(state.season), N.fetchSeason(state.previous_season), N.fetchProjections(state.season),
    N.fetchPlayers(), N.fetchTrending("add", 200), N.fetchSchedule(state.season),
  ]);
  const weeks = [];
  for (let w = state.week; w >= Math.max(1, state.week - 1); w--) weeks.push(await N.fetchWeek(state.season, w));

  const today = new Date().toISOString().slice(0, 10);
  const targets = pickNbaWaivers({
    state, season, previous, weeks, projections, players, adds, schedule, today,
    points: (stats) => N.fantasyPoints(stats, SCORING),
  });
  for (const t of targets) console.log(`${t.priority.padEnd(11)} ${t.name} (${t.team}) ${t.recent} FPG`);

  const head = { updatedOn: today, season: state.season, week: state.week, scoring: SCORING };
  const body = `${HEADER}{\n${Object.entries(head).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n` +
    `  "targets": [\n${targets.map((t) => `    ${JSON.stringify(t)}`).join(",\n")}\n  ]\n};\n`;
  if (DRY_RUN) return console.log("Dry run — file not written.");
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${targets.length} targets to ${OUT}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
