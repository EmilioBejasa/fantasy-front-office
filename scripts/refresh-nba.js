#!/usr/bin/env node
// Rewrites data/nba-snapshot.js from Sleeper: the NBA state, season totals for
// this season and last, the trimmed player list, and this season's last few
// fantasy weeks (every week would grow to ~4MB by April; older weeks are
// still there live).
//
// Usage: node scripts/refresh-nba.js [--dry-run]
//
// The basketball pages pull all of this live from Sleeper (see
// lib/sleeper-nba.js); the snapshot is what they fall back to when Sleeper
// can't be reached, including from a plain double-clicked index.html.

const fs = require("fs");
const path = require("path");
const N = require("./lib/sleeper-nba");

const OUT = path.join(__dirname, "..", "data", "nba-snapshot.js");
const DRY_RUN = process.argv.includes("--dry-run");
const KEEP_WEEKS = 3;
const HEADER = "// Generated by scripts/refresh-nba.js — don't edit by hand.\nwindow.NBA_SNAPSHOT = ";

async function main() {
  // Sleeper sends the state's fields in no fixed order, so pick them out in
  // one, or every run would look like a change.
  const s = await N.fetchState();
  const state = {};
  for (const k of ["season", "previous_season", "league_season", "season_type", "week", "season_start_date"]) state[k] = s[k];
  // Keyed like the page's nbaCached keys, so the fallback is a plain lookup.
  const data = { state };
  for (const s of [state.season, state.previous_season]) {
    data[`season-${s}`] = await N.fetchSeason(s);
    console.log(`Season ${s}: ${data[`season-${s}`].length} players`);
  }
  data.players = await N.fetchPlayers();
  console.log(`${Object.keys(data.players).length} active players`);

  const weeks = state.season_type === "regular" ? state.week : state.season_type === "post" ? 25 : 0;
  for (let w = Math.max(1, weeks - KEEP_WEEKS + 1); w <= weeks; w++) {
    // Kept even when empty (a week before its first game), so the Scoreboard
    // can tell it's empty and open on last week.
    const players = await N.fetchWeek(state.season, w);
    data[`week-${state.season}-${w}`] = players;
    console.log(`Week ${w}: ${players.length} players`);
  }

  // Only rewrite when the data changed, so scheduled runs don't commit no-ops.
  const json = JSON.stringify(data);
  try {
    const before = fs.readFileSync(OUT, "utf8");
    if (JSON.stringify(eval(`(${before.slice(HEADER.length).replace(/;\s*$/, "")})`).data) === json) {
      return console.log("NBA data unchanged — snapshot left as is.");
    }
  } catch (e) {}

  const body = `${HEADER}{"updatedOn":"${new Date().toISOString().slice(0, 10)}","data":${json}};\n`;
  console.log(`Snapshot is ${(body.length / 1024).toFixed(0)} KB`);
  if (DRY_RUN) return console.log("Dry run — snapshot not written.");
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
