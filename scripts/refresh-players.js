#!/usr/bin/env node
// Rewrites data/nfl-players.js: Sleeper's NFL player list trimmed to what the
// app uses (names, teams, injury designations, bio lines).
//
// Usage: node scripts/refresh-players.js [--dry-run]
//
// The page loads this instead of the full ~2.5MB list, and only falls back to
// Sleeper if the file is missing or more than 12 hours old (see
// fetchSleeperPlayerMap in index.html).

const fs = require("fs");
const path = require("path");
const { fetchPlayers } = require("./lib/sleeper-players");

const OUT = path.join(__dirname, "..", "data", "nfl-players.js");
const DRY_RUN = process.argv.includes("--dry-run");
const HEADER = "// Generated by scripts/refresh-players.js — don't edit by hand.\nwindow.NFL_PLAYERS = ";

async function main() {
  const players = await fetchPlayers();
  // Sorted ids, so the file only changes when a player does.
  const sorted = Object.fromEntries(Object.keys(players).sort().map((id) => [id, players[id]]));
  const json = JSON.stringify(sorted);
  console.log(`${Object.keys(sorted).length} players`);

  try {
    const before = fs.readFileSync(OUT, "utf8");
    if (JSON.stringify(eval(`(${before.slice(HEADER.length).replace(/;\s*$/, "")})`).players) === json) {
      return console.log("Players unchanged — file left as is.");
    }
  } catch (e) {}

  // A full timestamp, since this runs several times a day.
  const body = `${HEADER}{"fetchedAt":${Date.now()},"players":${json}};\n`;
  console.log(`File is ${(body.length / 1024).toFixed(0)} KB`);
  if (DRY_RUN) return console.log("Dry run — file not written.");
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
