#!/usr/bin/env node
// Rewrites data/prospects-2027.js, the college production behind the 2027
// Class tab and its prospect pages, from ESPN (see lib/espn-college.js) for
// every CLASS_2027 entry with an `espnId`.
//
// Usage: node scripts/refresh-prospects.js [--dry-run]

const fs = require("fs");
const path = require("path");
const { fetchProspect } = require("./lib/espn-college");
const { extractBlock } = require("./lib/bake");

const INDEX_HTML = path.join(__dirname, "..", "index.html");
const OUT = path.join(__dirname, "..", "data", "prospects-2027.js");
const DRY_RUN = process.argv.includes("--dry-run");
const HEADER = "// Generated by scripts/refresh-prospects.js — don't edit by hand.\nwindow.PROSPECTS_2027 = ";
const CONCURRENCY = 4;

async function main() {
  const source = fs.readFileSync(INDEX_HTML, "utf8");
  const list = eval(extractBlock(source, "const CLASS_2027 = [", "\n];").text.replace(/^const CLASS_2027 = /, ""));
  const todo = list.filter((p) => p.espnId);
  const missing = list.filter((p) => !p.espnId).map((p) => p.name);
  if (missing.length) console.log(`No espnId (skipped): ${missing.join(", ")}`);

  const teamCache = new Map();
  const players = {};
  let failed = 0;
  for (let i = 0; i < todo.length; i += CONCURRENCY) {
    await Promise.all(todo.slice(i, i + CONCURRENCY).map(async (p) => {
      try {
        players[p.espnId] = await fetchProspect(p.espnId, p.position, teamCache);
        console.log(`${p.name}: ${players[p.espnId].seasons.length} seasons`);
      } catch (err) {
        failed++;
        console.error(`${p.name}: ${err.message}`);
      }
    }));
  }
  // A partial outage shouldn't wipe out prospects that were there before.
  if (failed > todo.length / 2) throw new Error(`${failed} of ${todo.length} prospects failed — file left as is.`);
  const before = readBefore();
  for (const p of todo) if (!players[p.espnId] && before?.players?.[p.espnId]) players[p.espnId] = before.players[p.espnId];

  const ordered = todo.map((p) => p.espnId).filter((id) => players[id]);
  const body = (updatedOn) => `${HEADER}{\n  "updatedOn": ${JSON.stringify(updatedOn)},\n  "players": {\n` +
    ordered.map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(players[id])}`).join(",\n") + "\n  }\n};\n";

  // Only bump the date when the data changed, so scheduled runs don't commit no-ops.
  if (before && body(before.updatedOn) === fs.readFileSync(OUT, "utf8")) return console.log("Prospect stats unchanged — file left as is.");
  if (DRY_RUN) return console.log("Dry run — file not written.");
  fs.writeFileSync(OUT, body(new Date().toISOString().slice(0, 10)));
  console.log(`Wrote ${OUT}`);
}

function readBefore() {
  try {
    return JSON.parse(fs.readFileSync(OUT, "utf8").slice(HEADER.length).replace(/;\s*$/, ""));
  } catch (e) {
    return null;
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
